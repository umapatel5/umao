import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import vm from "node:vm";
import ts from "typescript";

const require = createRequire(import.meta.url);
const source = readFileSync(new URL("../lib/webcam/candidate-webcam.ts", import.meta.url), "utf8");
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const module = { exports: {} };
vm.runInNewContext(output, { exports: module.exports, module, require, Date });
const { createWebcamMetrics, emptyWebcamMetrics, markWebcamAnalysisUnavailable } = module.exports;
const face = { x: 100, y: 70, width: 200, height: 200 };
const sample = (previous, timestamp, faces = [face], headPosition = "centered") => createWebcamMetrics({ previous, timestamp, faces, headPosition, frameWidth: 480, frameHeight: 360 });
const centered = sample(emptyWebcamMetrics, 1000);
assert.equal(centered.faceState, "detected");
assert.equal(centered.lookingAwayMs, 0);
const turned = sample(centered, 1500, [face], "left");
assert.equal(turned.lookingAwayCount, 1);
assert.equal(turned.lookingAwayMs, 500);
const absent = sample(turned, 2000, []);
assert.equal(absent.faceState, "not-detected");
assert.equal(absent.lookingAwayCount, 1);
const recovered = sample(absent, 2500);
assert.equal(recovered.extendedAwayMs, 0);
const gap = sample(centered, 100000, []);
assert.equal(gap.lookingAwayMs, 1500);
const unavailable = markWebcamAnalysisUnavailable(centered);
assert.equal(unavailable.analysisAvailable, false);
assert.equal(sample(unavailable, Date.now() + 10000, []).lookingAwayMs, 0);
console.log("Webcam metrics checks passed: face presence, head direction, recovery, unavailable analysis, and paused-frame gaps.");
